const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('pip', {
  ignoreMouse: (on) => ipcRenderer.send('win:ignore', on),
  moveWindow: (x, y) => ipcRenderer.send('win:move', { x, y }),
  ttsAvailable: () => ipcRenderer.invoke('tts:available'),
  ttsSpeak: (req) => ipcRenderer.invoke('tts:speak', req),
  dragStart: () => ipcRenderer.send('drag:start'),
  resizeStart: () => ipcRenderer.send('resize:start'),
  resizeEnd: () => ipcRenderer.invoke('resize:end'),
  expand: (on) => ipcRenderer.invoke('win:expand', on),
  dragEnd: () => ipcRenderer.invoke('drag:end'),
  onDragMoved: (fn) => ipcRenderer.on('drag:moved', () => fn()),
  windowPos: () => ipcRenderer.invoke('win:pos'),
  hide: () => ipcRenderer.send('win:hide'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  ask: (req) => ipcRenderer.invoke('ai:ask', req),
  listProviders: () => ipcRenderer.invoke('providers:list'),
  saveProvider: (draft) => ipcRenderer.invoke('providers:save', draft),
  deleteProvider: (id) => ipcRenderer.invoke('providers:delete', id),
  activateProvider: (id) => ipcRenderer.invoke('providers:activate', id),
  testProvider: (draft, keysText) => ipcRenderer.invoke('providers:test', { draft, keysText }),
  providerModels: (draft, keysText) => ipcRenderer.invoke('providers:models', { draft, keysText }),
  openUrl: (url) => ipcRenderer.invoke('open:url', url),
  activeExcel: () => ipcRenderer.invoke('excel:active'),
  recentExcel: () => ipcRenderer.invoke('excel:recent'),
  officeMake: (kind, payload) => ipcRenderer.invoke('office:make', { kind, payload }),
  readClipboard: () => ipcRenderer.invoke('clip:read'),
  showWindow: () => ipcRenderer.send('win:show'),
  addReminder: (at, text) => ipcRenderer.invoke('remind:add', { at, text }),
  listReminders: () => ipcRenderer.invoke('remind:list'),
  removeReminder: (id) => ipcRenderer.invoke('remind:remove', id),
  onReminder: (fn) => ipcRenderer.on('reminder:due', (_e, r) => fn(r)),
  onClipboardKey: (fn) => ipcRenderer.on('ui:clipboard', () => fn()),
  excelChart: (chart) => ipcRenderer.invoke('excel:chart', chart),
  copyImage: (dataUrl) => ipcRenderer.invoke('clip:image', dataUrl),
  savePng: (dataUrl, name) => ipcRenderer.invoke('file:savePng', { dataUrl, name }),
  openApp: (name) => ipcRenderer.invoke('open:app', name),
  closeApp: (name) => ipcRenderer.invoke('close:app', name),
  onSettingsChanged: (fn) => ipcRenderer.on('ui:settings', () => fn()),
  models: () => ipcRenderer.invoke('ai:models'),
  readFile: (p) => ipcRenderer.invoke('file:read', p),
  pickFile: () => ipcRenderer.invoke('file:pick'),
  pickFolder: () => ipcRenderer.invoke('folder:pick'),
  pathOf: (file) => webUtils.getPathForFile(file),
  runTask: (task, folder) => ipcRenderer.invoke('task:run', { task, folder }),
  todayNote: () => ipcRenderer.invoke('note:today'),
  copy: (t) => ipcRenderer.invoke('clip:write', t),
  mailDraft: (subject, body) => ipcRenderer.invoke('mail:draft', { subject, body }),
  onChunk: (fn) => ipcRenderer.on('ai:chunk', (_e, d) => fn(d)),
  onOpen: (fn) => ipcRenderer.on('ui:open', (_e, what) => fn(what)),
  onPushToTalk: (fn) => ipcRenderer.on('ui:ptt', () => fn()),
});
